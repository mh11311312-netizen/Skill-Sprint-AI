def status_bar(counts, width=493):
    total = sum(counts.values()) or 1
    d = Drawing(width, 34)
    x = 0
    order = ["Verified", "Verified with Warning", "Partially Verified", "Manual Review Required", "Contradiction Detected",
             "Unsupported Requirement", "Source Support Missing", "Outdated Source", "Requirement Missing", "Optional Not Included"]
    fills = {"ok": GREEN, "info": GOLD, "warn": RED, "note": BLUE}
    for k in order:
        v = counts.get(k, 0)
        if not v:
            continue
        w = width * v / total
        d.add(Rect(x, 14, w, 16, fillColor=fills[STATUS_KIND[k]] if k != "Optional Not Included" else LINE, strokeColor=colors.white, strokeWidth=0.8))
        if w > 38:
            d.add(String(x + 4, 19, f"{v}", fontName="Sans-B", fontSize=7.5, fillColor=colors.white))
        x += w
    d.add(String(0, 2, "  ".join(f"{k}: {counts[k]}" for k in order if counts.get(k)), fontName="Sans", fontSize=6.8, fillColor=MUTED))
    return d


