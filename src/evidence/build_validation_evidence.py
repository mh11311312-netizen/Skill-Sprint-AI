def comparison_rows(b):
    out = []
    for p in b["plans"]:
        for r in p.get("rows", []):
            g, py = r.get("genai"), r.get("python")
            st = r["status"]
            if g is None:
                match = "Not generated"
            elif py is None:
                match = "Mismatch"
            else:
                match = "Match" if st == "Verified" and all(r.get("field_matches", {}).values()) else "Mismatch"
            if st == "Requirement Missing":
                cov = "Missing"
            elif st == "Optional Not Included":
                cov = "Not required"
            elif py and py.get("mandatory") and st in ("Verified", "Verified with Warning", "Partially Verified"):
                cov = "Covered"
            elif py and not py.get("mandatory"):
                cov = "Covered (optional)"
            else:
                cov = "Not counted"
            tr = {"valid": "Traced", "missing": "Source not found", "outdated": "Outdated source", "untrusted": "Untrusted source",
                  "quarantined": "Quarantined source"}.get(r.get("source_check"), "-")
            out.append({"Requirement ID": r["requirement_id"], "Role": p["role"],
                        "Source": (py or {}).get("source") or (g or {}).get("source") or "-",
                        "Python expected requirement": (f"{(py or {}).get('text', '')} [{'Mandatory' if py.get('mandatory') else 'Optional'}, {py.get('due_stage')}]" if py else
                                                        (f"Not expected: {r['explanation'].split('Source is ')[-1].rstrip('.')}" if "overridden by" in (r.get("explanation") or "")
                                                         else "Not in this role's matrix")),
                        "GenAI result": (f"{'Mandatory' if g.get('mandatory') else 'Optional'}, {g.get('due_stage')}, cites {g.get('source')} ({r.get('module_id')})" if g else "Not generated"),
                        "Match/Mismatch": match, "Coverage status": cov, "Traceability status": tr, "Validation status": st,
                        "Explanation of disagreement": r.get("explanation") or ("-" if match == "Match" else "")})
    return out


